def plot_recommendations(query_idx, embeddings, filenames, data_path, top_n=5):
    query_vec = embeddings[query_idx].reshape(1, -1)
    sims = cosine_similarity(query_vec, embeddings).flatten()
    indices = np.argsort(-sims)[1:top_n+1]

    plt.figure(figsize=(20, 4))
    plt.subplot(1, top_n + 1, 1)
    plt.imshow(Image.open(os.path.join(data_path, filenames[query_idx])))
    plt.title("CONSULTA")
    plt.axis('off')

    for i, idx in enumerate(indices):
        plt.subplot(1, top_n + 1, i + 2)
        plt.imshow(Image.open(os.path.join(data_path, filenames[idx])))
        plt.title(f"Sim {i+1} ({sims[idx]:.2f})")
        plt.axis('off')
    plt.show()

query_idx = np.random.randint(0, len(filenames))
