import tensorflow as tf
import os

data_path = '/content/Fashion_data/categories'
cats = sorted([d for d in os.listdir(data_path) if os.path.isdir(os.path.join(data_path, d))])

gen_params = dict(rescale=1./255, validation_split=0.2)
flow_params = dict(target_size=(224, 224), batch_size=32, interpolation='bilinear')

# Geradores simplificados
train_gen = tf.keras.preprocessing.image.ImageDataGenerator(rotation_range=20, horizontal_flip=True, **gen_params).flow_from_directory(data_path, subset='training', shuffle=True, **flow_params)
valid_gen = tf.keras.preprocessing.image.ImageDataGenerator(**gen_params).flow_from_directory(data_path, subset='validation', shuffle=False, **flow_params)
full_gen = tf.keras.preprocessing.image.ImageDataGenerator(rescale=1./255).flow_from_directory(data_path, shuffle=False, **flow_params)

# 1. Definição Única do Modelo (Standardized naming)
base_model = tf.keras.applications.ResNet50(weights='imagenet', include_top=False, input_shape=(224, 224, 3))
base_model.trainable = False # Inicialmente congelado

x = tf.keras.layers.GlobalAveragePooling2D()(base_model.output)
x = tf.keras.layers.Dropout(0.2)(x)
embedding_layer = tf.keras.layers.Dense(512, activation='relu', name='embedding_layer')(x)
predictions = tf.keras.layers.Dense(len(cats), activation='softmax', name='predictions')(embedding_layer)

model = tf.keras.models.Model(inputs=base_model.input, outputs=predictions)
model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001), loss='categorical_crossentropy', metrics=['accuracy'])

# Extrator de features padronizado referenciando a camada interna
feature_extractor = tf.keras.models.Model(inputs=model.input, outputs=model.get_layer('embedding_layer').output)

print("Modelo e feature_extractor únicos definidos. Base inicial congelada.")

print("Etapa 1: Treinando apenas as camadas superiores...")
model.fit(train_gen, epochs=2, validation_data=valid_gen)

